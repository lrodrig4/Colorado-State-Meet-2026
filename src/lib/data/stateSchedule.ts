export type StateMeetScheduleRound = "Prelim" | "Final";

export interface StateMeetScheduleSlot extends StateMeetScheduleItem {
  round: StateMeetScheduleRound;
}

type ScheduleSession = StateMeetScheduleItem["session"];
type ScheduleDay = StateMeetScheduleItem["day"];
type ScheduleRow = Omit<StateMeetScheduleSlot, "id">;

const SOURCE_FILE = "2025_2026_State_Track_Schedule_all_days.pdf";

function row(
  day: ScheduleDay,
  session: ScheduleSession,
  startTime: string,
  classification: Classification,
  gender: Gender,
  event: string,
  round: StateMeetScheduleRound,
): ScheduleRow {
  return {
    day,
    session,
    startTime,
    classification,
    gender,
    event,
    round,
    sourceFile: SOURCE_FILE,
  };
}

